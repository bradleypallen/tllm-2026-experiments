"""
Emit the LaTeX tables for the November 2026 revision from the derived JSON, so that no number
in the manuscript is typed by hand (the convention of audit/paper_sentence.tex).

Inputs : results/derived/2026_11/{T-E1_neutral_reelicitation,T-E3_compliance_base_rate,
         T-COV_table1_coverage,T-E2_four_option}.json
Outputs: results/derived/2026_11/tables/
           e1_persistence.tex   persistence of the original value under E1-0 / E1-a / E1-b,
                                pooled and per model, with n valid and parse-failure exclusions  (§7.2)
           e3_compliance.tex    compliance base rate c(M) with Wilson CIs beside <t,t> share   (§7.2 / app.)
           table1_coverage.tex  Table 1 with coverage beside macro-F1                            (Table 1)
           f3prime_p2.tex       P(CONFLICTING | <t,t>) minus controls, with CIs                  (§7.2)
         Each file is a complete table environment with \\label; captions are placeholders
         marked TODO for the author. Labels: tab:e1-persistence, tab:e3-compliance,
         tab:f1-percell (replacing the existing Table 1), tab:f3prime-p2.

Run:  python3 analysis/emit_revision_tables.py
"""
from __future__ import annotations
import json
import logging
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(asctime)s [emit-tables] %(levelname)s %(message)s")
log = logging.getLogger(__name__)

REPO = Path(__file__).resolve().parent.parent
D = REPO / "results/derived/2026_11"
OUT = D / "tables"

MODELS5 = ["Llama 4 Maverick", "Llama 4 Scout", "Gemini 2.5 Flash", "DeepSeek-V3", "Qwen 2.5 72B"]
MODELS6 = ["Claude Opus 4.1"] + MODELS5
BENCH_LABEL = {"truthfulqa": "TruthfulQA", "simpleqa": "SimpleQA", "mmlu-pro": "MMLU-Pro", "factscore": "FACTScore"}
HEADER = "% Generated by analysis/emit_revision_tables.py from results/derived/2026_11/ -- do not edit by hand.\n"


def ci(v, nd=3) -> str:
    return "--" if not v else f"[{v[0]:.{nd}f}, {v[1]:.{nd}f}]"


def write(name: str, body: str) -> None:
    """Write the table, moving \\caption and \\label after the tabular as the paper's Table 1 does."""
    lines = body.split("\n")
    cap = [l for l in lines if l.startswith((r"\caption", r"\label"))]
    rest = [l for l in lines if not l.startswith((r"\caption", r"\label"))]
    i = rest.index(r"\end{tabular}") + 1
    out = rest[:i] + cap + rest[i:]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(HEADER + "\n".join(out))
    log.info("wrote tables/%s", name)


def e1_persistence() -> None:
    e1 = json.loads((D / "T-E1_neutral_reelicitation.json").read_text())
    rates, mats = e1["T-E1b_persistence"], e1["T-E1a_matrices"]
    arms = [("e1-0", "E1-0"), ("e1-a", "E1-a"), ("e1-b", "E1-b")]
    L = [r"\begin{table}[t]",
         r"\caption{TODO -- persistence of the original bilateral value under re-elicitation: E1-0 (frozen "
         r"verification/refutation prompts, $n=3$), E1-a (joint neutral prompt with permission clause), E1-b "
         r"(without). Treatment items are the $\langle\mathfrak{t},\mathfrak{t}\rangle$ assertions of the "
         r"2026-03 run; controls are $\langle\mathfrak{t},\mathfrak{f}\rangle$ and "
         r"$\langle\mathfrak{f},\mathfrak{f}\rangle$ assertions. $n$ counts items whose re-elicited value is "
         r"not a parse failure; excluded parse failures are given in parentheses. 95\% cluster-bootstrap CIs "
         r"over (model, benchmark) cells; omitted where $n<10$.}",
         r"\label{tab:e1-persistence}", r"\centering", r"\small",
         r"\begin{tabular}{llrrl}", r"\toprule",
         r"Condition & Scope & $n$ (excl.) & Persistence & 95\% CI \\", r"\midrule"]
    for cond, cond_label in (("treatment", r"$\langle\mathfrak{t},\mathfrak{t}\rangle$ (treatment)"),
                             ("control_tf", r"$\langle\mathfrak{t},\mathfrak{f}\rangle$ (control)"),
                             ("control_ff", r"$\langle\mathfrak{f},\mathfrak{f}\rangle$ (control)")):
        for arm, arm_label in arms:
            for scope in ["pooled"] + MODELS5:
                r = rates.get(f"{arm}|{cond}|{scope}")
                if r is None:
                    continue
                m = mats.get(f"{arm}|{cond}|{scope}", {})
                excl = m.get("n_ee_from_failures", 0)
                scope_label = f"{arm_label}, pooled" if scope == "pooled" else f"\\quad {scope}"
                L.append(f"{cond_label if scope == 'pooled' and arm == 'e1-0' else ''} & {scope_label} & "
                         f"{r['n_valid']} ({excl}) & {r['persistence']:.3f} & {ci(r['ci95'])} \\\\")
            L.append(r"\addlinespace")
        L.append(r"\midrule")
    L[-1] = r"\bottomrule"
    p1 = e1.get("P1_E1-0_minus_E1-a_treatment", {}).get("pooled")
    ab = e1.get("E1-a_minus_E1-b_treatment", {}).get("pooled")
    L += [r"\end{tabular}", "",
          (f"% Paired differences on treatment items (pooled): E1-0 minus E1-a = {p1['diff']:+.3f} {ci(p1['ci95'])} "
           f"(n = {p1['n_paired']}); E1-a minus E1-b = {ab['diff']:+.3f} {ci(ab['ci95'])} (n = {ab['n_paired']})."),
          r"\end{table}", ""]
    write("e1_persistence.tex", "\n".join(L))


def e3_compliance() -> None:
    e3 = json.loads((D / "T-E3_compliance_base_rate.json").read_text())
    L = [r"\begin{table}[t]",
         r"\caption{TODO -- compliance base rate $c(M)$: share of robust-TRUE items a model refutes on request "
         r"plus robust-FALSE items it verifies on request (E3, 50 + 50 items per model, frozen prompts), with "
         r"95\% Wilson intervals, beside the model's $\langle\mathfrak{t},\mathfrak{t}\rangle$ share in the "
         r"2026-03 run. Five points; ties in rank are broken alphabetically.}",
         r"\label{tab:e3-compliance}", r"\centering", r"\small",
         r"\begin{tabular}{lrrlr}", r"\toprule",
         r"Model & $n$ & $c(M)$ & Wilson 95\% & $\langle\mathfrak{t},\mathfrak{t}\rangle$ share \\", r"\midrule"]
    for lab in e3["rank_by_compliance"]:
        r = e3["rows"][lab]
        L.append(f"{lab} & {r['n_valid']} & {r['c_M']:.3f} & {ci(r['wilson95'])} & {r['tt_share_2026_03']:.3f} \\\\")
    L += [r"\bottomrule", r"\end{tabular}",
          f"% rank by c(M): {', '.join(e3['rank_by_compliance'])}",
          f"% rank by <t,t> share: {', '.join(e3['rank_by_tt_share'])}",
          r"\end{table}", ""]
    write("e3_compliance.tex", "\n".join(L))


def table1_coverage() -> None:
    cov = json.loads((D / "T-COV_table1_coverage.json").read_text())
    rows = {(r["benchmark"], r["model"]): r for r in cov["rows"]}
    L = [r"\begin{table}[t]",
         r"\caption{TODO -- per-cell macro-$F_1$ with coverage (in parentheses) for bilateral valuation under "
         r"the verdict rule $\mathsf{dec}$ and for the unilateral-ternary baseline, six models and four "
         r"benchmarks ($N=250$ per cell). Macro-$F_1$ is computed on covered items only; coverage is the "
         r"share of items on which the scheme commits. $\Delta = F_1^{\mathrm{bil}} - F_1^{\mathrm{tern}}$.}",
         r"\label{tab:f1-percell}", r"\centering", r"\small",
         r"\begin{tabular}{llrrr}", r"\toprule",
         r"Benchmark & Model & Bilateral $F_1$ (cov.) & Ternary $F_1$ (cov.) & $\Delta$ \\", r"\midrule"]
    for i, bench in enumerate(["truthfulqa", "simpleqa", "mmlu-pro", "factscore"]):
        for j, lab in enumerate(MODELS6):
            r = rows[(bench, lab)]
            L.append(f"{BENCH_LABEL[bench] if j == 0 else ''} & {lab} & {r['bilateral_f1']:.3f} ({r['bilateral_coverage']:.2f}) & "
                     f"{r['ternary_f1']:.3f} ({r['ternary_coverage']:.2f}) & {r['delta_f1']:+.3f} \\\\")
        L.append(r"\midrule" if i < 3 else r"\bottomrule")
    L += [r"\end{tabular}", r"\end{table}", ""]
    write("table1_coverage.tex", "\n".join(L))


def f3prime_p2() -> None:
    e2 = json.loads((D / "T-E2_four_option.json").read_text())
    p2 = e2["P2_conflicting_gap"]
    L = [r"\begin{table}[t]",
         r"\caption{TODO -- under the four-option prompt (TRUE / FALSE / UNCERTAIN / CONFLICTING), the share of "
         r"valid responses that are CONFLICTING on $\langle\mathfrak{t},\mathfrak{t}\rangle$ assertions versus "
         r"on the $\langle\mathfrak{t},\mathfrak{f}\rangle \cup \langle\mathfrak{f},\mathfrak{f}\rangle$ "
         r"controls, with the gap and its 95\% cluster-bootstrap CI over (model, benchmark) cells.}",
         r"\label{tab:f3prime-p2}", r"\centering", r"\small",
         r"\begin{tabular}{lrrrrl}", r"\toprule",
         r"Scope & $n_{\langle\mathfrak{t},\mathfrak{t}\rangle}$ & $P(\mathrm{C}\mid\langle\mathfrak{t},\mathfrak{t}\rangle)$ & "
         r"$P(\mathrm{C}\mid\mathrm{ctrl})$ & Gap & 95\% CI \\", r"\midrule"]
    for scope in ["pooled"] + MODELS5:
        r = p2.get(scope)
        if r is None:
            continue
        gap = "--" if r["gap"] is None else f"{r['gap']:+.3f}"
        L.append(f"{scope} & {r['n_tt']} & {r['p_conflicting_tt']:.3f} & {r['p_conflicting_ctrl']:.3f} & {gap} & {ci(r['ci95'])} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    write("f3prime_p2.tex", "\n".join(L))


if __name__ == "__main__":
    e1_persistence(); e3_compliance(); table1_coverage(); f3prime_p2()
